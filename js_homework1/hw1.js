// 1. 'number' + 3 + 3
// Результат: 'number33'
// Чому: Конкатенація. Рядок плюс число завжди дає рядок.

// 2. null + 3
// Результат: 3
// Чому: При математичних операціях null перетворюється на 0. Тому 0 + 3 = 3.

// 3. 5 && "qwerty"
// Результат: 'qwerty'
// Чому: Логічне І (&&) повертає останнє true, оскільки 5 — це true, переходимо до рядка.

// 4. +'40' + +'2' + "hillel"
// Результат: '42hillel'
// Чому: Унарні плюси роблять з рядків числа (40 і 2), в сумі 42. Далі йде конкатенація з текстом.

// 5. '10' - 5 === 6
// Результат: false
// Чому: При відніманні рядок '10' стає числом, тобто 10 - 5 = 5. А 5 === 6 — це брехня.

// 6. true + false
// Результат: 1
// Чому: У математиці true — це 1, а false — це 0. Отже, 1 + 0 = 1.

// 7. '4px' - 3
// Результат: NaN
// Чому: '4px' не може стати нормальним числом через літери, тому маємо NaN. А NaN мінус будь-що = NaN.

// 8. '4' - 3
// Результат: 1
// Чому: При відніманні рушій JS сам перетворює рядок '4' на число.

// 9. '6' + 3 ** 0
// Результат: '61'
// Чому: Пріоритет у піднесення до степеня (3**0 = 1). Далі звичайна конкатенація '6' + 1.

// 10. 12 / '6'
// Результат: 2
// Чому: Рядок '6' автоматично перетворюється на число під час ділення.

// 11. '10' + (5 === 6)
// Результат: '10false'
// Чому: 5 === 6 повертає false. Далі рядок '10' зливається (конкатенація) з булевим false.

// 12. null == ''
// Результат: false
// Чому: При несуворому порівнянні null дорівнює тільки самому собі та undefined.

// 13. 3 ** (9 / 3)
// Результат: 27
// Чому: Спочатку в дужках отримуємо 3. Далі 3 в 3-му степені дорівнює 27.

// 14. !!'false' == !!'true'
// Результат: true
// Чому: Будь-який непустий рядок (навіть слово 'false') — це true. Тому маємо true == true.

// 15. 0 || '0' && 1
// Результат: 1
// Чому: && має вищий пріоритет. '0' (це true) && 1 повертає 1. Далі 0 (це false) || 1 шукає перше true і знаходить 1.

// 16. (+null == false) < 1
// Результат: false
// Чому: +null дає 0. 0 == false — це true. При порівнянні true стає одиницею, а 1 < 1 — це хибно.

// 17. false && true || true
// Результат: true
// Чому: Пріоритет у &&: false && true одразу дає false. Далі false || true шукає true і знаходить його в кінці.

// 18. false && (false || true)
// Результат: false
// Чому: В дужках отримуємо true. Але перед ними стоїть false &&, яке одразу обриває перевірку і повертає false.

// 19. (+null == false) < 1 ** 5
// Результат: false
// Чому: +null це 0. 0 == false дає true. 1**5 це 1. true (тобто 1) < 1 повертає false.
